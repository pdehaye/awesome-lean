#!/usr/bin/env bash
# Count how many cloned repos use each Lean language feature (rough ripgrep patterns).
# Usage: cd <clone-dir> && bash feature_scan.sh   (skips the lean4 compiler repo and the Lean Pool aggregate)
f() { name="$1"; pat="$2"; n=0; ex=""; for d in */; do d=${d%/}; [ "$d" = "leanprover__lean4" ] && continue; [ "$d" = "LeanPool__lean-pool" ] && continue; c=$(rg -c --type-add 'lean:*.lean' -t lean -e "$pat" "$d" 2>/dev/null | awk -F: '{s+=$NF} END{print s+0}'); if [ "$c" -gt 0 ]; then n=$((n+1)); ex="$ex ${d#*__}:$c"; fi; done; top=$(echo $ex | tr ' ' '\n' | sort -t: -k2 -nr | head -5 | tr '\n' ' '); printf "%-34s %3d repos | %s\n" "$name" "$n" "$top"; }
f "custom syntax categories" 'declare_syntax_cat'
f "macro / macro_rules" '^\s*(scoped |local )?macro(_rules)?\b'
f "elab / elab_rules" '^\s*(scoped |local )?elab(_rules)?\b'
f "notation/infix" '^\s*(scoped |local )?(notation|infixl?|infixr|prefix|postfix)\b'
f "custom attributes" 'registerBuiltinAttribute|register_simp_attr|registerTagAttribute|registerParametricAttribute|register_label_attr'
f "environment extensions" 'registerSimplePersistentEnvExtension|registerPersistentEnvExtension|registerEnvExtension|SimpleScopedEnvExtension|registerScopedEnvExtension'
f "options (register_option)" 'register_option|register_builtin_option'
f "initialize blocks" '^\s*(builtin_)?initialize\b'
f "delaborators/unexpanders" '@\[\s*(delab|app_unexpander|builtin_delab)'
f "deriving handlers" 'registerDerivingHandler'
f "deriving (uses)" '\bderiving\b'
f "simprocs" '^\s*(dsimproc|simproc)\b'
f "grind" '\bgrind\b'
f "Decidable instances" 'instance[^:]*:\s*Decidable'
f "decide +kernel" 'decide \+kernel|decide\s*\(\s*kernel'
f "native_decide" 'native_decide'
f "reflection (ofReduceBool)" 'ofReduceBool|Lean\.reduceBool'
f "@[extern]" '@\[\s*extern'
f "@[export]" '@\[\s*export'
f "@[implemented_by]" 'implemented_by'
f "@[csimp]" '@\[\s*csimp'
f "unsafe defs" '^\s*(private |protected )?unsafe\s+def'
f "partial defs" '\bpartial\s+def'
f "termination_by" 'termination_by'
f "Quotients" '\bQuotient\b|\bQuot\.'
f "#print axioms / CollectAxioms" '#print axioms|collectAxioms|CollectAxioms'
f "axiom declarations" '^\s*axiom\b'
f "opaque" '^\s*(private )?opaque\b'
f "monad transformers" '\b(StateT|ReaderT|ExceptT|OptionT|StateRefT)\b'
f "do-notation custom (ForIn/MonadLift)" 'instance[^:]*:\s*(ForIn|MonadLift|MonadExcept|Bind|Monad)\b'
f "coercions" 'instance[^:]*:\s*Coe'
f "typeclass outParam" 'outParam'
f "run_meta / run_cmd" '^\s*(run_meta|run_cmd|run_elab)\b'
f "#guard_msgs tests" '#guard_msgs'
f "widgets / RPC" '@\[\s*widget|@\[\s*server_rpc_method|Widget\.Module'
f "InfoTree / Frontend API" 'InfoTree|Frontend\.|IO\.processCommands|runFrontend'
f "Lake custom targets/facets" 'module_facet|library_facet|package_facet|target\s+\w+|extern_lib'
f "JSON (ToJson/FromJson)" 'ToJson|FromJson'
f "string interpolation s!/m!" 's!"|m!"|f!"'
f "Std.Do / mvcgen" 'mvcgen|Std\.Do'
f "Lean.Meta.Sym" 'Lean\.Meta\.Sym|Meta\.Sym\.'
f "universe polymorphism" '^\s*universe\b'
f "module system (module/public import)" '^\s*module\s*$|^public import|^meta import'
f "scoped instances/namespaces as switches" 'scoped instance|scoped\[|open scoped'
